import assert from 'node:assert/strict';
process.env.BETA_GUILD_ID = '1486680755869323388';
process.env.GUILD_ID = '1533088766821007390';
const { communityArrow, loadCommunityMotion, communityArrowKey, communityArrowName } = await import('../src/services/communityMotionService.js');
const { loadEmbedMotion, embedMotionKey, saveEmbedMotion, runWithMessageGuild } = await import('../src/services/embedMotionService.js');
const { installCommunityArrow } = await import('./install-community-arrow.mjs');
const guildId = process.env.BETA_GUILD_ID;
const artwork = { enabled: true, thumbnailUrl: 'https://cdn.discordapp.com/attachments/123/456/dexzu-motion-avatar.gif', bannerUrl: 'https://cdn.discordapp.com/attachments/123/457/dexzu-motion-giveaway.gif' };
const emoji = { id: '1549999999999999999', name: communityArrowName, animated: true };
const store = new Map([[embedMotionKey(guildId), artwork], [communityArrowKey, emoji]]);
let fail = false;
const client = { db: { get: async key => store.get(key), set: async (key, value) => { if (fail) return false; store.set(key, value); return true; } } };
await loadEmbedMotion(client);
await loadCommunityMotion(client);
assert.equal(communityArrow(guildId), `<a:${emoji.name}:${emoji.id}>`);
assert.equal(runWithMessageGuild(guildId, () => communityArrow()), `<a:${emoji.name}:${emoji.id}>`);
assert.equal(communityArrow(null), '◆');
assert.equal(communityArrow('111111111111111111'), '◆');
await saveEmbedMotion(client, guildId, false);
assert.equal(communityArrow(guildId), '◆');
await saveEmbedMotion(client, guildId, true);
store.set(communityArrowKey, { ...emoji, animated: false });
await loadCommunityMotion(client);
assert.equal(communityArrow(guildId), '◆');
store.set(communityArrowKey, emoji);
await loadCommunityMotion(client);
await assert.rejects(loadCommunityMotion({ db: { get: async () => { throw new Error('Unavailable'); } } }));
assert.equal(communityArrow(guildId), '◆', 'Failed load must clear cached emoji');
const items = [];
let creates = 0;
const rest = { get: async () => ({ items }), post: async () => { creates++; items.push(emoji); return emoji; } };
const input = { rest, applicationId: '123456789012345678', client, image: Buffer.from('GIF89a-test') };
fail = true;
await assert.rejects(installCommunityArrow(input));
assert.equal(creates, 1);
fail = false;
assert.equal((await installCommunityArrow(input)).reused, true);
assert.equal(creates, 1, 'Retry after storage failure must reuse upload');
assert.deepEqual(store.get(communityArrowKey), emoji);
await assert.rejects(installCommunityArrow({ ...input, image: Buffer.from('png') }));
items[0] = { ...emoji, animated: false };
await assert.rejects(installCommunityArrow(input));
assert.equal(creates, 1, 'Invalid existing emoji must not cause duplicate creation');
console.log('Community motion: guild settings, static fallback, stale cache, and idempotent install checks passed.');
