import assert from 'node:assert/strict';
import { PermissionsBitField } from 'discord.js';
process.env.BETA_GUILD_ID = '1486680755869323388';
const { getCommunityConfig, saveCommunityConfig, assertBetaFeature, assertCommunityReviewer, notifyCommunityMember } = await import('../src/services/communityBetaService.js');
const id = process.env.BETA_GUILD_ID, main = '1533088766821007390', values = new Map(); let fail = false, sent = 0;
const member = { id: '111111111111111111', permissions: new PermissionsBitField(), roles: { cache: new Map() }, send: async () => { sent++; } };
const guild = { id, roles: { cache: new Map(), fetch: async () => {} }, channels: { fetch: async () => null }, members: { fetch: async () => member } };
const client = { db: { get: async k => values.get(k), set: async (k,v) => { if (fail) return false; values.set(k, structuredClone(v)); return true; } } };
assert.equal((await getCommunityConfig(client,id)).features.inviteRewards,false);
await assert.rejects(assertBetaFeature(client,main,'inviteRewards'));
await saveCommunityConfig(client,guild,{features:{inviteRewards:true}});
assert.equal((await assertBetaFeature(client,id,'inviteRewards')).features.inviteRewards,true);
fail=true; await assert.rejects(saveCommunityConfig(client,guild,{features:{inviteRewards:false}})); fail=false;
assert.equal((await getCommunityConfig(client,id)).features.inviteRewards,true);
await assert.rejects(saveCommunityConfig(client,{...guild,id:main},{features:{inviteRewards:true}}));
await assert.rejects(saveCommunityConfig(client,guild,{milestones:[{invites:2,coins:-1}]}));
await assert.rejects(saveCommunityConfig(client,guild,{features:{applications:true}}));
assert.throws(()=>assertCommunityReviewer(guild,member,{}));
assert.equal((await notifyCommunityMember(client,guild,member.id,'tickets',{})).reason,'disabled'); assert.equal(sent,0);
await saveCommunityConfig(client,guild,{dmUpdates:{tickets:true}});
assert.equal((await notifyCommunityMember(client,guild,member.id,'tickets',{})).sent,true); assert.equal(sent,1);
member.send=async()=>{throw new Error('DM closed');};
assert.equal((await notifyCommunityMember(client,guild,member.id,'tickets',{})).sent,false);
assert.ok([...values.keys()].every(key=>!key.includes(main)));
console.log('Community foundation passed: beta gate, strict settings, failure persistence, permissions, optional DMs.');
