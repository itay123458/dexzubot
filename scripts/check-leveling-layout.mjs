import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const html = readFileSync(new URL('../src/web/public/index.html', import.meta.url), 'utf8');
const app = readFileSync(new URL('../src/web/public/app.js', import.meta.url), 'utf8');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
assert.equal(new Set(ids).size, ids.length, 'Controls must retain unique IDs');
const elements = new Map(ids.map(id => [id, { value: '', checked: false, textContent: '', disabled: false }]));
const $ = id => { assert.ok(elements.has(id), `Missing control: ${id}`); return elements.get(id); };
const context = vm.createContext({ $, state: null });
vm.runInContext(app.match(/function validateLeveling\(\) \{[\s\S]*?\n\}/)[0], context);
for (const [id, value] of Object.entries({ 'leveling-xp-min': '20', 'leveling-xp-max': '30', 'leveling-cooldown': '15', 'leveling-multiplier': '1' })) $(id).value = value;
assert.equal(vm.runInContext('validateLeveling()', context), true);
assert.equal($('save-leveling').disabled, false, 'Valid settings remain saveable without the removed summary');
$('leveling-xp-min').value = '40';
assert.equal(vm.runInContext('validateLeveling()', context), false);
assert.equal($('save-leveling').disabled, true);
assert.ok($('leveling-error').textContent.length > 0, 'Invalid XP range remains visible');
for (const id of ['leveling-enabled','leveling-announce','leveling-channel','level-reward-level','level-reward-role','add-level-reward','level-reward-list','save-level-rewards','reset-leveling']) $(id);
console.log('PASS: leveling controls and validation survive the layout change');
